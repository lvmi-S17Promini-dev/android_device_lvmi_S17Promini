#!/usr/bin/env python3
"""Extract vendor blobs and rebuild ext4 using stock ownership and labels."""
import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import tempfile

DEVICE = Path(__file__).resolve().parents[1]
ANDROID = DEVICE.parents[2]
VENDOR = ANDROID / "vendor/lvmi/S17Promini"
CONFIG = DEVICE / "vendor-config"
HOST = ANDROID / "out/host/linux-x86/bin"
PARTITION_SIZE = 1427996672


def run(*args):
    if str(args[0]) == "debugfs":
        # Android filters PATH tools; this metadata reader is a host dependency.
        args = (os.environ.get("S17_DEBUGFS", "/usr/sbin/debugfs"), *args[1:])
    env = os.environ.copy()
    env["PATH"] = str(HOST) + os.pathsep + env.get("PATH", "")
    p = subprocess.run(list(map(str, args)), capture_output=True, text=True, env=env)
    if p.returncode:
        raise RuntimeError(f"{args[0]} failed ({p.returncode}):\n{p.stdout}\n{p.stderr}")
    return p.stdout


def entries(filename):
    paths = [line for line in (DEVICE / filename).read_text().splitlines()
             if line and not line.startswith("#")]
    if len(paths) != len(set(paths)) or any(not p.startswith("vendor/") or
            ".." in PurePosixPath(p).parts or any(c.isspace() for c in p) for p in paths):
        raise ValueError(f"Invalid blob list: {filename}")
    return set(paths)


def image_metadata(image):
    paths, pending = {"/": 0o040000}, ["/"]
    while pending:
        directory = pending.pop()
        for line in run("debugfs", "-R", "ls -p " + directory, image).splitlines():
            f = line.split("/")
            if len(f) < 7 or not f[1].isdigit() or int(f[1]) == 0 or f[5] in (".", ".."):
                continue
            path = str(PurePosixPath(directory) / f[5])
            paths[path] = int(f[2], 8) & 0o170000
            if paths[path] == 0o040000:
                pending.append(path)
    with tempfile.NamedTemporaryFile("w") as commands:
        commands.write("\n".join(f"stat {p}\nea_get {p} security.selinux" for p in sorted(paths)))
        commands.flush()
        stats = run("debugfs", "-f", commands.name, image)
    result = {}
    for block in stats.split("debugfs: stat ")[1:]:
        path = block.splitlines()[0]
        owner = re.search(r"User:\s+(\d+)\s+Group:\s+(\d+).*Size:\s+(\d+)", block)
        mode = re.search(r"Mode:\s+([0-7]+)", block)
        label = re.search(r'security.selinux \(\d+\) = "([^"\\]+)', block)
        if not owner or not mode or not label:
            raise RuntimeError(f"Incomplete metadata: {path}")
        # No capability xattrs exist in the stock image; reject unhandled ones.
        if "security.capability" in block:
            raise RuntimeError(f"Capability metadata requires explicit support: {path}")
        info = {"kind": paths[path], "mode": int(mode[1], 8), "uid": int(owner[1]),
                "gid": int(owner[2]), "size": int(owner[3]), "selinux": label[1]}
        if paths[path] == 0o120000:
            target = re.search(r'Fast link dest: "([^"\n]+)"', block)
            if not target:
                raise RuntimeError(f"Unsupported long symlink: {path}")
            info["target"] = target[1]
        result["vendor" + (path if path != "/" else "")] = info
    if len(result) != len(paths):
        raise RuntimeError("Incomplete inode metadata")
    return result


def dump_files(image, destination, files):
    destination.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w") as commands:
        for path in files:
            target = destination / path
            target.parent.mkdir(parents=True, exist_ok=True)
            commands.write(f"dump {path.removeprefix('vendor')} {target}\n")
        commands.flush()
        run("debugfs", "-f", commands.name, image)


def configs(metadata):
    root = metadata["vendor"]
    # e2fsdroid also looks up the unprefixed filesystem root (empty path).
    (CONFIG / "fs_config").write_text(
        f" {root['uid']} {root['gid']} {root['mode']:04o} capabilities=0x0\n" +
        "\n".join(f"{p} {m['uid']} {m['gid']} {m['mode']:04o} capabilities=0x0"
                  for p, m in sorted(metadata.items())) + "\n")
    (CONFIG / "file_contexts").write_text("# Exact stock inode labels, including symlinks.\n" +
        "\n".join(f"/{re.escape(p)} {m['selinux']}" for p, m in sorted(metadata.items())) + "\n")


def setup():
    metadata = json.loads((CONFIG / "metadata.json").read_text())
    configs(metadata)
    VENDOR.mkdir(parents=True, exist_ok=True)
    (VENDOR / "BoardConfigVendor.mk").write_text(
        "# Generated by device/lvmi/S17Promini/setup-makefiles.sh.\n"
        "# Android.mk builds this input from expanded blobs, not a stock image.\n"
        "BOARD_PREBUILT_VENDORIMAGE := $(OUT_DIR)/target/product/S17Promini/obj/PACKAGING/s17_vendor_intermediates/vendor.img\n")
    (VENDOR / "S17Promini-vendor.mk").write_text(
        "# Generated by device/lvmi/S17Promini/setup-makefiles.sh.\n"
        "# Preserve stock CIL/properties; use the file-based image rule in Android.mk.\n"
        "PRODUCT_BUILD_VENDOR_IMAGE := false\n")
    files = sorted(p for p, m in metadata.items() if m["kind"] != 0o040000)
    make = """# Generated by device/lvmi/S17Promini/setup-makefiles.sh.
ifeq ($(TARGET_PRODUCT),lineage_S17Promini_system)
s17_vendor_dir := $(call my-dir)
s17_vendor_image := $(PRODUCT_OUT)/obj/PACKAGING/s17_vendor_intermediates/vendor.img
s17_vendor_inputs := $(addprefix $(s17_vendor_dir)/proprietary/, \\
""" + " \\\n".join("    " + p for p in files) + ")\n"
    make += """$(s17_vendor_image): PRIVATE_S17_VENDOR_DIR := $(s17_vendor_dir)
$(s17_vendor_image): $(s17_vendor_inputs) \\
    device/lvmi/S17Promini/tools/vendor-blobs.py \\
    device/lvmi/S17Promini/proprietary-files.txt \\
    device/lvmi/S17Promini/vendor-config/metadata.json \\
    device/lvmi/S17Promini/vendor-config/fs_config \\
    device/lvmi/S17Promini/vendor-config/file_contexts \\
    $(HOST_OUT_EXECUTABLES)/mkuserimg_mke2fs $(HOST_OUT_EXECUTABLES)/mke2fs \\
    $(HOST_OUT_EXECUTABLES)/e2fsdroid $(HOST_OUT_EXECUTABLES)/avbtool \\
    $(HOST_OUT_EXECUTABLES)/fec $(HOST_OUT_EXECUTABLES)/img2simg
	@echo "Building S17Promini vendor from expanded blobs"
	python3 device/lvmi/S17Promini/tools/vendor-blobs.py build --source $(PRIVATE_S17_VENDOR_DIR)/proprietary/vendor --output $@
endif
"""
    (VENDOR / "Android.mk").write_text(make)
    (VENDOR / ".gitignore").write_text("/proprietary/vendor.img\n/proprietary/vendor.json\n")


def extract(image):
    image = image.resolve()
    if not image.is_file() or image.stat().st_size != PARTITION_SIZE:
        raise ValueError("Input must be the original raw logical vendor.img")
    keep, removed = entries("proprietary-files.txt"), entries("proprietary-files-removed.txt")
    original = image_metadata(image)
    regular = {p for p, info in original.items() if info["kind"] == 0o100000}
    if regular != keep | removed or keep & removed:
        raise RuntimeError("Stock image does not match the keep/removal lists")
    deleted_apps = set()
    for p in removed:
        parts = PurePosixPath(p).parts
        if parts[1] == "app":
            deleted_apps.add("/".join(parts[:3]))
        elif parts[1:3] == ("operator", "app"):
            deleted_apps.add("/".join(parts[:4]))
    metadata = {p: info for p, info in original.items() if p not in removed and
                not any(p == app or p.startswith(app + "/") for app in deleted_apps)}
    VENDOR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="s17-extract-", dir=VENDOR) as temp:
        staging = Path(temp)
        for p, info in metadata.items():
            # mke2fs supplies lost+found. e2fsdroid skips its permission fixup.
            if info["kind"] == 0o040000 and p != "vendor/lost+found":
                (staging / p).mkdir(parents=True, exist_ok=True)
        dump_files(image, staging, sorted(keep))
        for p, info in metadata.items():
            if info["kind"] == 0o120000:
                (staging / p).symlink_to(info["target"])
            elif info["kind"] == 0o100000:
                if not (staging / p).is_file() or (staging / p).stat().st_size != info["size"]:
                    raise RuntimeError(f"Extraction failed: {p}")
        target = VENDOR / "proprietary/vendor"
        if target.exists():
            shutil.rmtree(target)
        target.parent.mkdir(parents=True, exist_ok=True)
        (staging / "vendor").replace(target)
    CONFIG.mkdir(exist_ok=True)
    # One inode per line keeps the versioned metadata easy to diff.
    (CONFIG / "metadata.json").write_text("{\n" + ",\n".join(
        "  " + json.dumps(p) + ": " + json.dumps(m, sort_keys=True)
        for p, m in sorted(metadata.items())) + "\n}\n")
    setup()
    print(f"Extracted {len(keep)} files and {sum('target' in m for m in metadata.values())} symlinks")


def digest(path):
    result = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(4 * 1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def build(source, output):
    source, output = source.resolve(), output.resolve()
    metadata = json.loads((CONFIG / "metadata.json").read_text())
    keep = entries("proprietary-files.txt")
    if keep != {p for p, m in metadata.items() if m["kind"] == 0o100000}:
        raise RuntimeError("Metadata is out of date; rerun extract-files.sh")
    actual = {"vendor/" + p.relative_to(source).as_posix()
              for p in source.rglob("*") if p.is_file() and not p.is_symlink()}
    if actual != keep:
        raise RuntimeError(f"Unexpected blob set: extra={actual - keep}, missing={keep - actual}")
    hashes = {p: digest(source / p.removeprefix("vendor/")) for p in keep}
    max_size = int(run(HOST / "avbtool", "add_hashtree_footer", "--partition_size",
                       PARTITION_SIZE, "--calc_max_image_size"))
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="s17-image-", dir=output.parent) as temp:
        temp = Path(temp)
        raw = temp / "vendor.img"
        run(HOST / "mkuserimg_mke2fs", source, raw, "ext4", "vendor", max_size,
            "-j", "0", "-T", "1230768000", "-C", CONFIG / "fs_config", "-L", "vendor",
            "-i", len(metadata) + 128, "-M", "0", CONFIG / "file_contexts")
        run("e2fsck", "-fn", raw)
        rebuilt = image_metadata(raw)
        if set(rebuilt) != set(metadata):
            raise RuntimeError(f"Image paths differ: extra={rebuilt.keys() - metadata.keys()}, missing={metadata.keys() - rebuilt.keys()}")
        for p, expected in metadata.items():
            for field in ("kind", "mode", "uid", "gid", "selinux", "target"):
                if rebuilt[p].get(field) != expected.get(field):
                    raise RuntimeError(f"Metadata mismatch {p} {field}: {rebuilt[p].get(field)} != {expected.get(field)}")
        check = temp / "payload-check"
        dump_files(raw, check, sorted(keep))
        for p, expected in hashes.items():
            if digest(check / p) != expected:
                raise RuntimeError(f"Payload mismatch: {p}")
        run(HOST / "avbtool", "add_hashtree_footer", "--image", raw,
            "--partition_name", "vendor", "--partition_size", PARTITION_SIZE,
            "--algorithm", "NONE", "--hash_algorithm", "sha256", "--do_not_use_ab")
        run(HOST / "avbtool", "verify_image", "--image", raw)
        sparse = temp / "vendor.sparse.img"
        run(HOST / "img2simg", raw, sparse)
        report = {"source": str(source), "output": str(output), "files": len(keep),
                  "symlinks": sum("target" in m for m in metadata.values()),
                  "expanded_size": PARTITION_SIZE, "sparse_size": sparse.stat().st_size,
                  "sha256": digest(sparse), "verified": "all payloads, owners, modes, labels, symlink targets, ext4 and AVB"}
        sparse.replace(output)
        output.with_suffix(".json").write_text(json.dumps(report, indent=2) + "\n")
        print(json.dumps(report, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    extract_cmd = sub.add_parser("extract")
    extract_cmd.add_argument("image", type=Path)
    sub.add_parser("setup")
    build_cmd = sub.add_parser("build")
    build_cmd.add_argument("--source", type=Path, default=VENDOR / "proprietary/vendor")
    build_cmd.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.command == "extract":
        extract(args.image)
    elif args.command == "setup":
        setup()
    else:
        build(args.source, args.output)
